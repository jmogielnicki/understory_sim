import { Noise2D, smoothstep, clamp, lerp } from '../util/Noise.js';
import { boxBlur } from './terrain/TerrainNoise.js';
import { PATHS, polylineDistance } from './terrain/Paths.js';
import { distanceTo } from './terrain/DistanceField.js';
import { loadTerrainFiles } from './terrain/TerrainFiles.js';

// height of the water surface where there is none (below every terrain height in the data)
export const NO_WATER = - 60;

const NEAR_BLEND = 48; // m: the near grid hands over to the mid grid over its outer band
const MID_BLEND = 192; // m: the mid grid hands over to the far grid

// Squam Lake, New Hampshire: measured terrain (USGS 3DEP lidar, see tools/terrain/build_terrain.py)
// in three nested grids, plus the masks the terrain material, the plants and the props read.
//
//   near  2048 m at 1 m: the walkable area (heights, masks, CDLOD terrain mesh)
//   mid   8192 m at 4 m: the lake around it and the hills behind (FarTerrain, heightAt)
//   far  32768 m at 16 m: the surrounding ranges and the other lakes (FarTerrain, heightAt)
// y = 0 is the surface of Squam Lake. The lake bed is generated by the build script.
//
// Masks on the near grid (1 m):
//   rock      bare granite: ledges and cliffs (Rattlesnake), rocky shore, boulder-strewn lake bed
//   sand      land: beaches in the gentle coves; lake bed: sand and gravel (silt where 0)
//   path      worn footpaths
//   gully     land: meadow / open ground (0 = forest floor); lake bed: pondweed and eelgrass beds
//   seagrass  the same lake-bed weed beds (kept separate for the systems that read it)
//   rubble    lake bed: cobbles and boulders (rocky shores, the shoals)
//   scarp     the eroded bank where the forest floor meets the water (roots, bare soil)
// shoreDist: signed distance to the shore (m), > 0 in the water.
export class TerrainData {

	static async load( seed = 7 ) {

		return new TerrainData( await loadTerrainFiles(), seed );

	}

	constructor( { meta, grids, water }, seed = 7 ) {

		const near = grids.near;
		this.meta = meta;
		this.size = near.size;
		this.res = near.res;
		this.texel = near.texel;
		this.origin = near.origin;
		this.heights = near.heights;
		this.mid = grids.mid;
		this.far = grids.far;
		this.water = water;
		this.waterLevels = new Float32Array( 256 ).fill( NO_WATER );
		for ( const b of water.bodies ) this.waterLevels[ b.id ] = b.level;

		this.noise = new Noise2D( seed );
		this.noise2 = new Noise2D( seed * 31 + 5 );
		this.noise3 = new Noise2D( seed * 131 + 17 );
		const n = this.res * this.res;
		this.rock = new Float32Array( n );
		this.sand = new Uint8Array( n );
		this.path = new Uint8Array( n );
		this.gully = new Uint8Array( n ); // open ground on land, weed beds on the lake bed
		this.seagrass = new Uint8Array( n );
		this.rubble = new Uint8Array( n );
		this.scarp = new Uint8Array( n );
		this.meadow = this.gully;
		this.rockSites = []; // outcrops for the rock scatter: { x, z, r, h, kind }
		this.pads = []; // building pads flattened by the village (trampled ground in the splat map)
		this.paths = PATHS;
		this.timings = {};
		this.generate();
		this.buildMinMax();

	}

	// signed distance to the lake shore (m): > 0 water, < 0 land
	coastDistance( x, z ) {

		const { res, texel, origin } = this;
		const i = Math.floor( ( x - origin ) / texel ), j = Math.floor( ( z - origin ) / texel );
		if ( i < 0 || j < 0 || i >= res || j >= res ) return { d: this.heightAt( x, z ) < 0 ? 60 : - 60, beachZone: 0 };
		return { d: this.shoreDist[ j * res + i ], beachZone: 0 };

	}

	// height of the water surface at (x, z): the lake (0), another lake or pond at its own level, or NO_WATER
	waterLevelAt( x, z ) {

		const w = this.water;
		const i = Math.floor( ( x - w.origin ) / w.texel ), j = Math.floor( ( z - w.origin ) / w.texel );
		if ( i < 0 || j < 0 || i >= w.res || j >= w.res ) return NO_WATER;
		return this.waterLevels[ w.ids[ j * w.res + i ] ];

	}

	// ------------------------------------------------------------------ generation

	generate() {

		const T = this.timings;
		let t = performance.now();
		const tick = ( name ) => {

			const now = performance.now();
			T[ name ] = Math.round( now - t );
			t = now;

		};

		this._blendEdges();
		tick( 'edges' );
		const res = this.res, H = this.heights;
		// signed distance to the shore, > 0 in the lake
		const toLand = distanceTo( res, res, ( k ) => H[ k ] >= 0 );
		const toWater = distanceTo( res, res, ( k ) => H[ k ] < 0 );
		const D = this.shoreDist = new Float32Array( res * res );
		for ( let k = 0; k < D.length; k ++ ) D[ k ] = H[ k ] < 0 ? toLand[ k ] * this.texel : - toWater[ k ] * this.texel;
		tick( 'shoreDist' );
		this._masks();
		tick( 'masks' );
		this._features();
		tick( 'features' );
		this.rock = boxBlur( this.rock, res, res, 1 );
		tick( 'blur' );
		T.total = Object.values( T ).reduce( ( a, b ) => a + b, 0 );

	}

	// the near grid fades into the mid grid over its outer band and the mid grid into the far grid, so the
	// three meet without a step (the coarser grids hold the block means of the finer ones inside them)
	_blendEdges() {

		const blend = ( g, coarse, band ) => {

			const { res, texel, origin, heights: H } = g;
			const nb = Math.ceil( band / texel );
			for ( let j = 0; j < res; j ++ ) {

				const ej = Math.min( j, res - 1 - j );
				for ( let i = 0; i < res; i ++ ) {

					const e = Math.min( i, res - 1 - i, ej );
					if ( e >= nb ) {

						i = res - 1 - nb; // skip the interior of the row
						continue;

					}

					const w = smoothstep( 1.5, band / texel, e );
					const k = j * res + i;
					H[ k ] = lerp( sampleGrid( coarse, origin + ( i + 0.5 ) * texel, origin + ( j + 0.5 ) * texel ), H[ k ], w );

				}

			}

		};

		blend( this.mid, this.far, MID_BLEND );
		blend( { res: this.res, texel: this.texel, origin: this.origin, heights: this.heights }, this.mid, NEAR_BLEND );

	}

	// rock, sand, open ground, the eroded bank and the lake-bed covers from the measured shape
	_masks() {

		const res = this.res, o = this.origin, H = this.heights, D = this.shoreDist;
		const n = this.noise, n2 = this.noise2, n3 = this.noise3;
		const rock = this.rock, sand = this.sand, weeds = this.gully, grass = this.seagrass, rubble = this.rubble, scarp = this.scarp;
		// lidar ground has decimetre bumps (stumps, rocks, the old road): judge slopes on a 2 m blur
		const Hs = boxBlur( H, res, res, 2 );
		// slope of the land at the nearest shore, carried a few metres out over the bed (rocky points
		// drop off steeply and keep cobbles, sheltered coves are sandy and weedy)
		for ( let j = 3; j < res - 3; j ++ ) {

			const z = o + j + 0.5;
			for ( let i = 3; i < res - 3; i ++ ) {

				const k = j * res + i;
				const h = H[ k ];
				const x = o + i + 0.5;
				const gx = ( Hs[ k + 2 ] - Hs[ k - 2 ] ) * 0.25, gz = ( Hs[ k + 2 * res ] - Hs[ k - 2 * res ] ) * 0.25;
				const slope = Math.sqrt( gx * gx + gz * gz );
				const d = D[ k ];
				const nz = n2.noise( x / 23, z / 23 ) * 0.5 + n3.noise( x / 7, z / 7 ) * 0.25;

				if ( h >= 0 ) {

					// ---- land
					const e = - d; // metres from the water
					// granite: cliffs and ledges, convex knobs on steep ground, the waterline of rocky shores
					const lap = ( Hs[ k + 3 ] + Hs[ k - 3 ] + Hs[ k + 3 * res ] + Hs[ k - 3 * res ] - 4 * Hs[ k ] ) / 9;
					let rk = smoothstep( 0.8 + nz * 0.25, 1.15 + nz * 0.25, slope );
					rk = Math.max( rk, smoothstep( 0.5, 0.85, slope ) * smoothstep( - 0.03, - 0.12, lap ) * 0.9 );
					const rockyShore = smoothstep( 0.18, 0.4, slope ) * ( 1 - smoothstep( 1.5 + nz * 2, 4 + nz * 3, e ) ) * smoothstep( - 0.1, 0.25, n.noise( x / 31, z / 31 ) + 0.15 );
					rk = Math.max( rk, rockyShore );
					rock[ k ] = clamp( rk, 0, 1 );

					// beach: the gentle shore of the coves, a few metres wide and less than a metre up
					const gentle = 1 - smoothstep( 0.07, 0.16, slope );
					const beach = gentle * ( 1 - smoothstep( 3 + nz * 4, 6 + nz * 6, e ) ) * ( 1 - smoothstep( 0.7, 1.3, h ) ) * smoothstep( - 0.25, 0.05, n.noise( x / 47, z / 47 ) );
					sand[ k ] = Math.round( clamp( beach * ( 1 - rk ), 0, 1 ) * 255 );

					// eroded bank: a low, steep step of bare soil and roots where the forest floor meets the water
					const bank = smoothstep( 0.45, 0.8, slope ) * ( 1 - smoothstep( 2.5, 4.5, e ) ) * smoothstep( 0.15, 0.4, h ) * ( 1 - smoothstep( 2.0, 3.2, h ) );
					scarp[ k ] = Math.round( clamp( bank * ( 1 - rk ) * ( 1 - beach ), 0, 1 ) * 255 );

				} else {

					// ---- lake bed
					const depth = - h;
					// sand and gravel in the shallows, silt in deep water; coarser off rocky points
					const sd = ( 1 - smoothstep( 1.2 + nz * 1.5, 3.5 + nz * 2, depth ) ) * smoothstep( - 0.3, 0.2, n.noise( x / 19, z / 19 ) + 0.1 );
					sand[ k ] = Math.round( clamp( sd, 0, 1 ) * 255 );
					// cobbles and boulders: off steep shores (the land slope carries over the first metres of the
					// bed, which then drops off steeply too) and patches elsewhere in the shallows
					const steepBed = smoothstep( 0.15, 0.4, slope ) * ( 1 - smoothstep( 6, 12, depth ) );
					const patches = smoothstep( 0.45, 0.62, n3.noise( x / 13 + 9.1, z / 13 - 2.2 ) + n.noise( x / 4.3, z / 4.3 ) * 0.3 ) * ( 1 - smoothstep( 3, 8, depth ) );
					rubble[ k ] = Math.round( clamp( Math.max( steepBed * ( 0.7 + nz * 0.6 ), patches * 0.8 ), 0, 1 ) * 255 );
					// weed beds: sheltered, gently sloping shallows from about half a metre to 4 m
					const win = smoothstep( 0.5, 1.1, depth ) * ( 1 - smoothstep( 3.2, 4.8, depth + nz * 1.5 ) );
					const f = n.fbm( x / 70, z / 70, 3 ) + n2.noise( x / 17, z / 17 ) * 0.25 + n3.noise( x / 6, z / 6 ) * 0.1;
					const g = smoothstep( 0.05, 0.25, f ) * win * ( 1 - smoothstep( 0.08, 0.2, slope ) ) * ( 1 - rubble[ k ] / 255 );
					weeds[ k ] = grass[ k ] = Math.round( clamp( g, 0, 1 ) * 255 );
					rock[ k ] = clamp( smoothstep( 0.6, 1.0, slope ) * ( 1 - smoothstep( 4, 12, depth ) ), 0, 1 );

				}

			}

		}

	}

	// discrete features: the shoal crests (cobble and boulder piles) and the footpaths
	_features() {

		const res = this.res, o = this.origin, H = this.heights, n2 = this.noise2;
		const Hb = boxBlur( H, res, res, 6 );
		for ( let j = 1; j < res - 1; j ++ ) for ( let i = 1; i < res - 1; i ++ ) {

			const k = j * res + i;
			if ( H[ k ] >= 0 ) continue;
			// a shoal stands proud of the smoothed bed
			const proud = smoothstep( 0.15, 0.6, H[ k ] - Hb[ k ] );
			if ( proud > 0 ) this.rubble[ k ] = Math.max( this.rubble[ k ], Math.round( proud * 255 ) );

		}

		for ( const p of PATHS ) {

			let x0 = Infinity, x1 = - Infinity, z0 = Infinity, z1 = - Infinity;
			for ( const [ px, pz ] of p.pts ) {

				x0 = Math.min( x0, px ); x1 = Math.max( x1, px ); z0 = Math.min( z0, pz ); z1 = Math.max( z1, pz );

			}

			const R = p.w * 2 + 2;
			const i0 = Math.max( 0, Math.floor( x0 - R - o ) ), i1 = Math.min( res - 1, Math.ceil( x1 + R - o ) );
			const j0 = Math.max( 0, Math.floor( z0 - R - o ) ), j1 = Math.min( res - 1, Math.ceil( z1 + R - o ) );
			for ( let j = j0; j <= j1; j ++ ) for ( let i = i0; i <= i1; i ++ ) {

				const x = o + i + 0.5, z = o + j + 0.5;
				const [ dist ] = polylineDistance( p.pts, x, z );
				const w = p.w * ( 1 + 0.25 * n2.noise( x / 6, z / 6 ) );
				const m = 1 - smoothstep( w * 0.6, w * 1.9, dist );
				if ( m <= 0 ) continue;
				const k = j * res + i;
				const v = Math.round( m * 255 );
				if ( v > this.path[ k ] ) this.path[ k ] = v;
				this.rock[ k ] *= 1 - m;
				// worn a few centimetres into the forest floor
				H[ k ] -= 0.06 * ( 1 - smoothstep( w * 0.4, w * 1.2, dist ) ) * smoothstep( 0.3, 1.0, H[ k ] );

			}

		}

	}

	// ------------------------------------------------------------------ edits / queries

	// flatten a circular pad (for building foundations)
	flatten( x, z, radius, height, falloff = 4 ) {

		const { res, texel, origin } = this;
		const r = radius + falloff;
		this.pads.push( { x, z, radius, height } );
		const i0 = Math.max( 0, Math.floor( ( x - r - origin ) / texel ) ), i1 = Math.min( res - 1, Math.ceil( ( x + r - origin ) / texel ) );
		const j0 = Math.max( 0, Math.floor( ( z - r - origin ) / texel ) ), j1 = Math.min( res - 1, Math.ceil( ( z + r - origin ) / texel ) );
		for ( let j = j0; j <= j1; j ++ ) for ( let i = i0; i <= i1; i ++ ) {

			const px = origin + ( i + 0.5 ) * texel, pz = origin + ( j + 0.5 ) * texel;
			const d = Math.hypot( px - x, pz - z );
			const t = 1 - smoothstep( radius, r, d );
			const k = j * res + i;
			this.heights[ k ] = lerp( this.heights[ k ], height, t );
			this.rock[ k ] *= 1 - t;

		}

	}

	// terrain height at (x, z): the near grid, else the mid grid, else the far grid (clamped at its edge)
	heightAt( x, z ) {

		const { res, texel, origin, heights } = this;
		const fx = ( x - origin ) / texel - 0.5, fz = ( z - origin ) / texel - 0.5;
		if ( fx < 0 || fz < 0 || fx >= res - 1 || fz >= res - 1 ) return sampleGrid( this._outer( x, z ), x, z );
		const i = Math.floor( fx ), j = Math.floor( fz );
		const tx = fx - i, tz = fz - j;
		const k = j * res + i;
		const a = heights[ k ], b = heights[ k + 1 ], c = heights[ k + res ], d = heights[ k + res + 1 ];
		return ( a * ( 1 - tx ) + b * tx ) * ( 1 - tz ) + ( c * ( 1 - tx ) + d * tx ) * tz;

	}

	_outer( x, z ) {

		const m = this.mid;
		const h = m.size / 2 - m.texel;
		return Math.abs( x ) < h && Math.abs( z ) < h ? m : this.far;

	}

	normalAt( x, z, out ) {

		const e = Math.abs( x ) < this.size / 2 && Math.abs( z ) < this.size / 2 ? this.texel : this._outer( x, z ).texel;
		const hx = this.heightAt( x + e, z ) - this.heightAt( x - e, z );
		const hz = this.heightAt( x, z + e ) - this.heightAt( x, z - e );
		out.set( - hx, 2 * e, - hz ).normalize();
		return out;

	}

	// distance (m) from (x, z) to the nearest footpath edge (negative inside a path)
	pathDistance( x, z ) {

		let best = Infinity;
		for ( const p of PATHS ) best = Math.min( best, polylineDistance( p.pts, x, z )[ 0 ] - p.w );
		return best;

	}

	// min/max pyramids for CDLOD culling bounds (near, mid and far grids)
	buildMinMax() {

		this.mmTile = 8;
		this.mm = {
			near: minMaxPyramid( { res: this.res, texel: this.texel, origin: this.origin, heights: this.heights }, 8 ),
			mid: minMaxPyramid( this.mid, 8 ),
			far: minMaxPyramid( this.far, 8 ),
		};
		this.mmLevels = this.mm.near.levels;

	}

	// [ min, max ] height over the box, from the finest grid that contains it
	boundsFor( x0, z0, x1, z1 ) {

		const inside = ( g ) => x0 >= g.origin && z0 >= g.origin && x1 <= g.origin + g.size && z1 <= g.origin + g.size;
		const near = { origin: this.origin, size: this.size };
		const p = inside( near ) ? this.mm.near : inside( this.mid ) ? this.mm.mid : this.mm.far;
		return p.bounds( x0, z0, x1, z1 );

	}

}

// bilinear sample of a grid at world (x, z), clamped at its edge
export function sampleGrid( g, x, z ) {

	const { res, texel, origin, heights } = g;
	let fx = ( x - origin ) / texel - 0.5, fz = ( z - origin ) / texel - 0.5;
	fx = fx < 0 ? 0 : fx > res - 1.001 ? res - 1.001 : fx;
	fz = fz < 0 ? 0 : fz > res - 1.001 ? res - 1.001 : fz;
	const i = Math.floor( fx ), j = Math.floor( fz );
	const tx = fx - i, tz = fz - j;
	const k = j * res + i;
	const a = heights[ k ], b = heights[ k + 1 ], c = heights[ k + res ], d = heights[ k + res + 1 ];
	return ( a * ( 1 - tx ) + b * tx ) * ( 1 - tz ) + ( c * ( 1 - tx ) + d * tx ) * tz;

}

function minMaxPyramid( g, tile ) {

	const { res, texel, origin, heights: H } = g;
	const n = res / tile;
	const mn0 = new Float32Array( n * n ), mx0 = new Float32Array( n * n );
	for ( let tj = 0; tj < n; tj ++ ) for ( let ti = 0; ti < n; ti ++ ) {

		let mn = Infinity, mx = - Infinity;
		const jEnd = Math.min( res - 1, ( tj + 1 ) * tile ), iEnd = Math.min( res - 1, ( ti + 1 ) * tile );
		for ( let j = tj * tile; j <= jEnd; j ++ ) {

			const row = j * res;
			for ( let i = ti * tile; i <= iEnd; i ++ ) {

				const h = H[ row + i ];
				if ( h < mn ) mn = h;
				if ( h > mx ) mx = h;

			}

		}

		mn0[ tj * n + ti ] = mn;
		mx0[ tj * n + ti ] = mx;

	}

	// coarser levels: level l has n >> l tiles per side
	const levels = [ { n, min: mn0, max: mx0 } ];
	let cur = levels[ 0 ];
	while ( cur.n > 1 ) {

		const m = cur.n >> 1;
		const mn = new Float32Array( m * m ), mx = new Float32Array( m * m );
		for ( let j = 0; j < m; j ++ ) for ( let i = 0; i < m; i ++ ) {

			const a = ( 2 * j ) * cur.n + 2 * i, b = a + cur.n;
			mn[ j * m + i ] = Math.min( cur.min[ a ], cur.min[ a + 1 ], cur.min[ b ], cur.min[ b + 1 ] );
			mx[ j * m + i ] = Math.max( cur.max[ a ], cur.max[ a + 1 ], cur.max[ b ], cur.max[ b + 1 ] );

		}

		cur = { n: m, min: mn, max: mx };
		levels.push( cur );

	}

	const bounds = ( x0, z0, x1, z1 ) => {

		// the pyramid level where the box spans only a few tiles per side
		const span = Math.max( x1 - x0, z1 - z0 ) / ( texel * tile );
		const l = Math.max( 0, Math.min( levels.length - 1, Math.ceil( Math.log2( Math.max( 1, span / 2 ) ) ) ) );
		const L = levels[ l ];
		const ts = texel * tile * ( 1 << l );
		const i0 = Math.max( 0, Math.floor( ( x0 - origin ) / ts ) ), i1 = Math.min( L.n - 1, Math.floor( ( x1 - origin ) / ts ) );
		const j0 = Math.max( 0, Math.floor( ( z0 - origin ) / ts ) ), j1 = Math.min( L.n - 1, Math.floor( ( z1 - origin ) / ts ) );
		let mn = Infinity, mx = - Infinity;
		for ( let j = j0; j <= j1; j ++ ) for ( let i = i0; i <= i1; i ++ ) {

			const k = j * L.n + i;
			if ( L.min[ k ] < mn ) mn = L.min[ k ];
			if ( L.max[ k ] > mx ) mx = L.max[ k ];

		}

		if ( mn > mx ) mn = mx = 0;
		return [ mn - 1, mx + 2 ];

	};

	return { levels, bounds };

}
